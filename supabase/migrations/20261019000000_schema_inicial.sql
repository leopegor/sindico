create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------------------
-- Função genérica de auditoria: mantém atualizado_em sincronizado em UPDATE.
-- ---------------------------------------------------------------------------
create or replace function public.set_atualizado_em()
returns trigger
language plpgsql
as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- unidades: Loja (comercial) + 10 apartamentos (residencial).
-- ---------------------------------------------------------------------------
create table if not exists public.unidades (
  id                     bigint generated by default as identity primary key,
  codigo                 text not null unique,
  nome_morador           text not null default '',
  numero_pessoas         integer not null default 0 check (numero_pessoas >= 0),
  area_privativa         numeric(12,4) not null default 0 check (area_privativa >= 0),
  fracao_ideal           numeric(12,8) not null default 0
                           check (fracao_ideal >= 0 and fracao_ideal <= 1),
  is_sindico             boolean not null default false,
  participa_policiamento boolean not null default false,
  valor_policiamento     numeric(12,2) not null default 0
                           check (valor_policiamento >= 0),
  tipo                   text not null default 'residencial'
                           check (tipo in ('residencial', 'comercial')),
  criado_em              timestamptz not null default now(),
  atualizado_em          timestamptz not null default now()
);

comment on table public.unidades is
  'Unidades condominiais: LOJA + 10 apartamentos do Edifício Evaristo Lucchese.';
comment on column public.unidades.fracao_ideal is
  'Fração ideal em fração decimal (ex.: 0.0838 = 8,38%).';

-- ---------------------------------------------------------------------------
-- competencias: apuração mensal das contas do condomínio.
-- ---------------------------------------------------------------------------
create table if not exists public.competencias (
  id                             bigint generated by default as identity primary key,
  mes_referencia                 text not null,
  ano_referencia                 integer not null
                                   check (ano_referencia between 2000 and 2200),
  data_vencimento                date not null,
  nome_sindico                   text not null,
  apto_sindico                   text not null,
  periodo_mandato                text default 'ago/2026 à jul/2027',
  -- Água (CORSAN)
  valor_conta_agua               numeric(12,2) not null default 0,
  valor_esgoto_total             numeric(12,2) not null default 0,
  taxa_minima_agua               numeric(12,2) not null default 0,
  consumo_agua_m3                numeric(12,3),
  fmrh                           numeric(12,2) not null default 0,
  -- Energia (RGE)
  consumo_energia_kwh            numeric(12,3),
  valor_conta_energia            numeric(12,2) not null default 0,
  -- Limpeza
  servicos_limpeza               numeric(12,2) not null default 0,
  materiais_limpeza              numeric(12,2) not null default 0,
  -- Outras despesas / fundo
  limpeza_caixas_agua            numeric(12,2) not null default 0,
  discriminacao_outras_despesas  text,
  fundo_manutencao_mensal        numeric(12,2) not null default 0,
  discriminacao_fundo_manutencao text,
  -- Seguro
  valor_apolice                  numeric(12,2)
                                   check (valor_apolice is null or valor_apolice >= 0),
  numero_parcelas                integer
                                   check (numero_parcelas is null or numero_parcelas between 1 and 12),
  -- Juros, multa e parâmetros de rateio
  juros_mora_mensal              numeric(8,6) not null default 0.015
                                   check (juros_mora_mensal >= 0),
  multa_mora                     numeric(8,6) not null default 0.02
                                   check (multa_mora >= 0),
  divisor_rateio_sindico         integer not null default 11
                                   check (divisor_rateio_sindico in (10, 11)),
  fator_atraso                   numeric(6,4) not null default 0.95
                                   check (fator_atraso > 0),
  observacoes                    text,
  criado_em                      timestamptz not null default now(),
  atualizado_em                  timestamptz not null default now(),
  constraint competencias_mes_referencia_check
    check (
      upper(translate(mes_referencia, 'ÇÁÃÂÉÊÍÓÔÕÚ', 'CAAAEEIOOOU')) in (
        'JANEIRO', 'FEVEREIRO', 'MARCO', 'ABRIL', 'MAIO', 'JUNHO',
        'JULHO', 'AGOSTO', 'SETEMBRO', 'OUTUBRO', 'NOVEMBRO', 'DEZEMBRO'
      )
    ),
  constraint competencias_periodo_unico unique (ano_referencia, mes_referencia)
);

comment on table public.competencias is
  'Competência mensal (apuração de água, energia, limpeza, seguro e rateio).';

create index if not exists competencias_periodo_idx
  on public.competencias (ano_referencia desc, data_vencimento desc);

-- ---------------------------------------------------------------------------
-- pagamentos: controle de quitação do mês por unidade.
-- ---------------------------------------------------------------------------
create table if not exists public.pagamentos (
  id             bigint generated by default as identity primary key,
  competencia_id bigint not null
                   references public.competencias (id)
                   on update cascade on delete cascade,
  unidade_codigo  text not null
                   references public.unidades (codigo)
                   on update cascade on delete restrict,
  pago           boolean not null default false,
  data_pagamento timestamptz,
  valor_pago     numeric(12,2) check (valor_pago is null or valor_pago >= 0),
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now(),
  constraint pagamentos_competencia_unidade_unique
    unique (competencia_id, unidade_codigo)
);

create index if not exists pagamentos_unidade_idx
  on public.pagamentos (unidade_codigo);

-- ---------------------------------------------------------------------------
-- dividas_anteriores: valor manual da dívida acumulada por unidade.
-- ---------------------------------------------------------------------------
create table if not exists public.dividas_anteriores (
  id             bigint generated by default as identity primary key,
  unidade_codigo text not null unique
                   references public.unidades (codigo)
                   on update cascade on delete cascade,
  valor          numeric(12,2) not null default 0 check (valor >= 0),
  atualizado_em  timestamptz not null default now(),
  criado_em      timestamptz not null default now()
);

comment on table public.dividas_anteriores is
  'Dívida anterior digitada manualmente (substitui o cálculo automático).';

-- ---------------------------------------------------------------------------
-- abatimentos_divida: pagamentos parciais sobre a dívida anterior.
-- ---------------------------------------------------------------------------
create table if not exists public.abatimentos_divida (
  id             bigint generated by default as identity primary key,
  unidade_codigo text not null
                   references public.unidades (codigo)
                   on update cascade on delete cascade,
  valor          numeric(12,2) not null check (valor > 0),
  data           timestamptz not null default now(),
  observacao     text,
  criado_em      timestamptz not null default now()
);

create index if not exists abatimentos_divida_unidade_idx
  on public.abatimentos_divida (unidade_codigo, data desc);

-- ---------------------------------------------------------------------------
-- Triggers de atualizado_em
-- ---------------------------------------------------------------------------
drop trigger if exists unidades_atualizado_em on public.unidades;
create trigger unidades_atualizado_em
  before update on public.unidades
  for each row execute function public.set_atualizado_em();

drop trigger if exists competencias_atualizado_em on public.competencias;
create trigger competencias_atualizado_em
  before update on public.competencias
  for each row execute function public.set_atualizado_em();

drop trigger if exists pagamentos_atualizado_em on public.pagamentos;
create trigger pagamentos_atualizado_em
  before update on public.pagamentos
  for each row execute function public.set_atualizado_em();
